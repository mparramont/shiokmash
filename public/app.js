// shiokmash frontend - confirm plus chop written in Singlish style lah

let curr_matchup   = null;   // current battle being displayed
let vote_cast_lah  = false;  // prevent double-voting like that kiasu uncle

// ── page routing ──────────────────────────────────────────────────────────────
function showPage(page_name) {
  document.querySelectorAll('.page').forEach(pg => pg.classList.remove('active'));
  document.querySelectorAll('.nav-btn').forEach(btn => btn.classList.remove('active'));

  document.getElementById(`page-${page_name}`).classList.add('active');
  document.getElementById(`btn-${page_name}`).classList.add('active');

  // fetch fresh leaderboard data when switching to that tab lah
  if (page_name === 'leaderboard') load_leaderboard_lah();
}

// ── matchup ───────────────────────────────────────────────────────────────────
async function loadMatchup() {
  vote_cast_lah = false;

  // reset card visuals before loading next matchup lah
  const card_one = document.getElementById('dish-one');
  const card_two = document.getElementById('dish-two');
  card_one.classList.remove('winner', 'loser');
  card_two.classList.remove('winner', 'loser');

  document.getElementById('vote-result').classList.add('hidden');
  document.getElementById('loading').classList.remove('hidden');
  document.querySelectorAll('.vote-btn').forEach(btn => (btn.disabled = false));

  try {
    const resp        = await fetch('/api/matchup');
    const shiok_data  = await resp.json();

    curr_matchup = shiok_data;

    // populate dish one card lah
    document.getElementById('emoji-one').textContent = shiok_data.dish_one.emoji;
    document.getElementById('name-one').textContent  = shiok_data.dish_one.name;
    document.getElementById('score-one').textContent = `${Math.round(shiok_data.dish_one.score)} pts`;
    card_one.dataset.id                              = shiok_data.dish_one.id;

    // populate dish two card lah
    document.getElementById('emoji-two').textContent = shiok_data.dish_two.emoji;
    document.getElementById('name-two').textContent  = shiok_data.dish_two.name;
    document.getElementById('score-two').textContent = `${Math.round(shiok_data.dish_two.score)} pts`;
    card_two.dataset.id                              = shiok_data.dish_two.id;

    // show the battle intro text generated by lahlang lah
    document.getElementById('battle-intro').textContent = shiok_data.intro;

  } catch (err) {
    console.error('Aiyah loadMatchup suay:', err);
    document.getElementById('battle-intro').textContent =
      'Aiyah cannot load matchup leh. Try refresh lah!';
  } finally {
    document.getElementById('loading').classList.add('hidden');
  }
}

// ── voting ────────────────────────────────────────────────────────────────────
async function castVote(dish_side) {
  if (vote_cast_lah) return;  // cannot vote twice lah - one person one vote only
  vote_cast_lah = true;

  document.querySelectorAll('.vote-btn').forEach(btn => (btn.disabled = true));

  const loser_side  = dish_side === 'one' ? 'two' : 'one';
  const winner_card = document.getElementById(`dish-${dish_side}`);
  const loser_card  = document.getElementById(`dish-${loser_side}`);
  const winner_id   = winner_card.dataset.id;
  const loser_id    = loser_card.dataset.id;
  const winner_name = document.getElementById(`name-${dish_side}`).textContent;

  // show winner/loser state immediately for responsiveness lah
  winner_card.classList.add('winner');
  loser_card.classList.add('loser');

  try {
    const resp       = await fetch('/api/vote', {
      method:  'POST',
      headers: { 'Content-Type': 'application/json' },
      body:    JSON.stringify({ winner_id, loser_id })
    });
    const vote_result = await resp.json();

    if (!resp.ok) throw new Error(vote_result.error || 'Vote kena reject lah');

    // calculate points gained for the result banner
    const prev_score    = curr_matchup[`dish_${dish_side}`].score;
    const points_gained = Math.round(vote_result.winner.new_score - prev_score);
    const gain_text     = points_gained > 0 ? ` (+${points_gained} pts)` : '';

    document.getElementById('result-text').textContent =
      `${winner_name} wins lah! Shiok!${gain_text}`;

    document.getElementById('vote-result').classList.remove('hidden');

  } catch (err) {
    console.error('Aiyah castVote suay:', err);
    document.getElementById('result-text').textContent =
      'Wah vote kena error leh. Try again lor.';
    document.getElementById('vote-result').classList.remove('hidden');
  }
}

// ── leaderboard ───────────────────────────────────────────────────────────────
async function load_leaderboard_lah() {
  const tbody      = document.getElementById('leaderboard-body');
  const commentary = document.getElementById('leaderboard-commentary');

  commentary.textContent = 'Loading lah…';
  tbody.innerHTML        = '';

  try {
    const resp          = await fetch('/api/leaderboard');
    const board_data    = await resp.json();

    // commentary text generated by lahlang lah
    commentary.textContent = board_data.commentary;

    board_data.leaderboard.forEach((dish, idx) => {
      const rank        = idx + 1;
      const rank_medal  = rank === 1 ? '🥇' : rank === 2 ? '🥈' : rank === 3 ? '🥉' : rank;
      const win_rate_lah = dish.total_votes > 0
        ? `${Math.round((dish.wins / dish.total_votes) * 100)}%`
        : '—';

      const tr = document.createElement('tr');
      tr.innerHTML = `
        <td><span class="rank-medal">${rank_medal}</span></td>
        <td>${dish.emoji} <strong>${dish.name}</strong></td>
        <td><strong>${Math.round(dish.score)}</strong></td>
        <td>${dish.wins}</td>
        <td>${dish.losses}</td>
        <td>${dish.total_votes} <small style="color:#999">(${win_rate_lah})</small></td>
      `;
      tbody.appendChild(tr);
    });

  } catch (err) {
    console.error('Aiyah load_leaderboard_lah suay:', err);
    commentary.textContent = 'Aiyah cannot load leh! Try refresh lor.';
  }
}

// ── boot ──────────────────────────────────────────────────────────────────────
// start the first matchup when page loads lah
loadMatchup();
